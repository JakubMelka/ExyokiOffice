// End-to-end tour of the high-level WordDocumentEditor API. It builds a small
// but complete report: properties, a title page, a table of contents, styled
// prose, body cursors, one- and multi-level lists, a formatted table, an image,
// hyperlinks and bookmarks, a footnote, an endnote, a comment, a content
// control, page fields in the footer, page setup, and a search-and-replace pass
// — then re-opens the saved file to prove the document round-trips.
//
// Editing an existing document is a separate example, examples/ExampleWordEdit;
// the low-level DOM/packaging path is demonstrated in examples/ExampleWord.
#include "Common/SampleImage.hpp"
#include "ExyokiOffice/Word/WordDocument.hpp"
#include "ExyokiOffice/StandardTypes.hpp"

#include <cstddef>
#include <cstdint>
#include <iostream>
#include <optional>
#include <string_view>

using namespace ExyokiOffice::Word;
namespace W = ExyokiOffice::DocumentFormat::OpenXml::Wordprocessing;
using ExyokiOffice::Color;
using ExyokiOffice::MeasurementUnit;
using ExyokiOffice::MeasuringUnits;

namespace ExampleWord
{

MeasuringUnits Millimeters(ExyokiOffice::Real value)
{
    return MeasuringUnits(value, MeasurementUnit::Millimeter);
}

MeasuringUnits Points(ExyokiOffice::Real value)
{
    return MeasuringUnits(value, MeasurementUnit::Point);
}

// Body prose used throughout the document. Real paragraphs make the generated
// file useful for eyeballing pagination, justification, and hyphenation.
constexpr std::string_view IntroductionText =
    "ExyokiOffice is a C++20 library for creating, opening, editing, and saving Office Open XML "
    "packages. It writes the ZIP container and its XML parts directly, so neither Microsoft Office "
    "nor a .NET runtime has to be installed on the machine that produces the document. This report "
    "was generated by examples/ExampleWordEditor and demonstrates the features a typical document "
    "generator needs.";

constexpr std::string_view LayeringText =
    "The library is layered. At the bottom sits the OPC package: parts, relationships, content "
    "types, and a lossless round-trip that keeps everything it does not understand. Above it lives "
    "the typed OpenXML DOM, generated from the published schema metadata, which turns every element "
    "and attribute into a checked C++ type. The high-level editors — WordDocumentEditor, "
    "ExcelDocumentEditor, and PowerPointDocumentEditor — sit on top and are what most applications "
    "actually use.";

constexpr std::string_view CursorText =
    "Content is inserted through cursors. Body() appends to the end of the document, while "
    "Before(block) and After(block) insert relative to an existing paragraph or table. Every "
    "insertion returns a wrapper that can be formatted further, so a document can be assembled in "
    "any order rather than strictly front to back.";

constexpr std::string_view FieldsText =
    "Fields are created but never evaluated: ExyokiOffice writes the field instruction and marks "
    "the result dirty, and Word computes the value when the document is opened. That keeps the "
    "library free of a layout engine while still producing page numbers, a table of contents, and "
    "cross-references that behave exactly as a user expects.";

} // namespace ExampleWord

int main()
{
    using namespace ExampleWord;

    // --- Create a new document and fill in its properties. -------------------
    auto editor = WordDocumentEditor::CreateNew();
    if (!editor)
    {
        std::cerr << "Failed to create the document.\n";
        return 1;
    }

    auto properties = editor->Properties();
    properties.SetTitle("ExyokiOffice Editor Example");
    properties.SetCreator("ExyokiOffice Library");
    properties.SetSubject("High-level Word API demonstration");
    properties.SetKeywords("ExyokiOffice, OpenXML, example");
    properties.SetDescription("Generated by examples/ExampleWordEditor.");
    properties.SetCategory("Samples");
    properties.SetContentStatus("Draft");
    properties.SetCompany("ExyokiOffice");

    // --- A custom paragraph style, used by the pull quote further down. ------
    auto styles = editor->Styles();
    StyleDefinition quote;
    quote.StyleId = "SampleQuote";
    quote.Name = "Sample Quote";
    quote.Type = StyleType::Paragraph;
    quote.BasedOnStyleId = "Normal";
    quote.NextStyleId = "Normal";
    quote.UiPriority = 29;
    styles.CreateStyle(quote);

    // --- Title page and table of contents. -----------------------------------
    auto title = editor->AddParagraph();
    title->SetAlignment(W::JustificationValues::Center).SetSpacing(Points(120.0), Points(12.0), std::nullopt);
    title->AddRun("ExyokiOffice", RunStyle{.Bold = true, .FontSize = Points(36.0)});
    auto subtitle = editor->AddParagraph("Generating Word documents from modern C++");
    subtitle->SetAlignment(W::JustificationValues::Center);
    subtitle->AddBookmark("Title");

    editor->AddPageBreak();
    editor->AddHeading("Contents", 1);
    editor->AddTableOfContents(1, 3);
    editor->AddParagraph("The entries above are filled in by Word when the fields are updated "
                         "(Ctrl+A, F9); ExyokiOffice writes the field, not the computed result.")
        ->SetSpacing(Points(6.0), Points(12.0), std::nullopt);
    editor->AddPageBreak();

    // --- Prose, headings, and run formatting. --------------------------------
    editor->AddHeading("Introduction", 1);
    editor->AddParagraph(IntroductionText)->SetAlignment(W::JustificationValues::Both);

    auto layering = editor->AddParagraph(LayeringText);
    layering->SetAlignment(W::JustificationValues::Both);
    layering->AddFootnote("The generated DOM covers WordprocessingML, SpreadsheetML, "
                          "PresentationML, DrawingML, and the shared namespaces.");

    editor->AddHeading("Text and formatting", 2);
    auto formatting = editor->AddParagraph();
    formatting->AddText("A paragraph is a sequence of runs, and a run is a stretch of uniformly "
                        "formatted text. Runs can mix ");
    formatting->AddRun("bold", RunStyle{.Bold = true});
    formatting->AddText(", ");
    formatting->AddRun("italic", RunStyle{.Italic = true});
    formatting->AddText(", ");
    formatting->AddRun()->SetUnderline(W::UnderlineValues(W::UnderlineValues::Single)).AddText("underlined");
    formatting->AddText(", ");
    formatting->AddRun()->SetSmallCaps().AddText("small caps");
    formatting->AddText(", ");
    formatting->AddRun()->SetColor(Color(0xC0, 0x00, 0x00)).SetFontSize(Points(14.0)).AddText("colored 14pt");
    formatting->AddText(", and ");
    formatting->AddRun()->SetHighlight(W::HighlightColorValues::Yellow).AddText("highlighted");
    formatting->AddText(" text.");
    formatting->AddBreak();
    formatting->AddText("An explicit line break keeps this sentence in the same paragraph, which "
                        "matters for spacing and for the paragraph-level search API.");

    auto pullQuote = editor->AddParagraph("Everything in this document is written through the public "
                                          "high-level API — no generated DOM element is touched.");
    pullQuote->SetStyleId("SampleQuote")
        .SetAlignment(W::JustificationValues::Center)
        .SetIndentation(Millimeters(20.0), Millimeters(20.0), std::nullopt, std::nullopt)
        .SetSpacing(Points(12.0), Points(12.0), std::nullopt)
        .SetShading(Color(0xF2, 0xF6, 0xFB))
        .SetBorders(W::BorderValues::Single, ExyokiOffice::UInt32{8}, Color(0x1F, 0x4E, 0x79), Points(6.0));

    auto cursors = editor->AddParagraph(CursorText);
    cursors->SetAlignment(W::JustificationValues::Both);

    // The cursors themselves. AddParagraph() is shorthand for
    // Body().InsertParagraph(); Before() and After() take an existing paragraph
    // or table as the anchor, which is how a document gets assembled out of
    // order — here a lead-in is placed above a paragraph that already exists,
    // and a two-row table lands directly underneath it.
    auto leadIn = editor->Before(cursors).InsertParagraph("Inserted afterwards, above the paragraph "
                                                          "that follows:");
    auto cursorTable = editor->After(cursors).InsertTable(2, 2);
    if (!leadIn || !cursorTable)
    {
        std::cerr << "Failed to insert content through the body cursors.\n";
        return 1;
    }
    leadIn->SetSpacing(Points(12.0), std::nullopt, std::nullopt);
    cursorTable->SetCellText(0, 0, "Body()");
    cursorTable->SetCellText(0, 1, "Appends at the end of the body");
    cursorTable->SetCellText(1, 0, "Before(x) / After(x)");
    cursorTable->SetCellText(1, 1, "Inserts next to an existing block");
    cursorTable->SetWidth(Millimeters(165.0))
        .SetBorders(W::BorderValues::Single, ExyokiOffice::UInt32{4}, Color(0x8E, 0xA9, 0xDB));

    // --- Lists: a simple bulleted list and a three-level numbered outline. ----
    editor->AddHeading("Lists", 2);
    editor->AddParagraph("Single-level lists need one call:");
    auto bullets = editor->EnsureBulletedListStyle();
    for (const auto* item : {"Paragraphs, runs, and text with full character formatting",
                             "Tables with merged cells, shading, and repeating header rows",
                             "Images with size, cropping, wrapping, and alt text",
                             "Fields, bookmarks, hyperlinks, footnotes, and comments"})
    {
        editor->AddParagraph(item)->SetListStyle(bullets);
    }

    editor->AddParagraph("Multi-level outlines are defined once and then applied per level:")
        ->SetSpacing(Points(12.0), std::nullopt, std::nullopt);

    NumberingDefinition outline;
    outline.Name = "SampleOutline";
    for (int level = 0; level < 3; ++level)
    {
        NumberingLevelDefinition definition;
        definition.Level = level;
        definition.Format = W::NumberFormatValues::Decimal;
        definition.LevelText = level == 0 ? "%1." : (level == 1 ? "%1.%2." : "%1.%2.%3.");
        definition.LeftIndent = Millimeters(10.0 * (level + 1));
        definition.HangingIndent = Millimeters(8.0);
        outline.Levels.push_back(definition);
    }
    auto outlineStyle = editor->Numbering().EnsureMultilevelList(outline);

    const struct
    {
        const char* text;
        int level;
    } outlineItems[] = {
        {"Open the package", 0},
        {"Read the relationships and content types", 1},
        {"Materialize only the parts that are touched", 1},
        {"Edit the content", 0},
        {"Work through the high-level editor", 1},
        {"Drop to the typed DOM when the editor does not model a feature", 1},
        {"Keep unknown markup untouched", 2},
        {"Save the package", 0},
    };
    for (const auto& item : outlineItems)
    {
        auto listStyle = outlineStyle;
        listStyle.Level = item.level;
        editor->AddParagraph(item.text)->SetListStyle(listStyle);
    }

    // --- A formatted table with a header row and a merged summary row. -------
    editor->AddHeading("Tables", 2);
    editor->AddParagraph("Tables are addressed by row and column, and support merging, shading, "
                         "widths, borders, and repeating header rows:");

    auto table = editor->AddTable(5, 4);
    table->SetWidth(Millimeters(165.0))
        .SetAlignment(W::TableRowAlignmentValues::center)
        .SetBorders(W::BorderValues::Single, ExyokiOffice::UInt32{6}, Color(0x8E, 0xA9, 0xDB))
        .SetDefaultCellMargins(Millimeters(2.0), Millimeters(1.0), Millimeters(2.0), Millimeters(1.0));

    // Table::Paragraphs() returns one paragraph per cell in row-major order, so
    // the still-empty header cells can be filled with formatted runs instead of
    // the plain text SetCellText() writes.
    const char* headers[] = {"Region", "Units", "Revenue", "Change"};
    auto headerCells = table->Paragraphs();
    for (ExyokiOffice::Size column = 0; column < 4; ++column)
    {
        headerCells[column]->AddRun(headers[column],
                                    RunStyle{.Bold = true, .Color = Color(0xFF, 0xFF, 0xFF)});
        table->SetCellBackgroundColor(0, column, Color(0x1F, 0x4E, 0x79));
    }
    table->SetRowHeader(0, true);

    const struct
    {
        const char* region;
        const char* units;
        const char* revenue;
        const char* change;
    } rows[] = {
        {"North", "1 240", "84 000", "+12 %"},
        {"South", "955", "66 500", "+4 %"},
        {"East", "1 610", "108 300", "+19 %"},
    };
    ExyokiOffice::Size rowIndex = 1;
    for (const auto& row : rows)
    {
        table->SetCellText(rowIndex, 0, row.region);
        table->SetCellText(rowIndex, 1, row.units);
        table->SetCellText(rowIndex, 2, row.revenue);
        table->SetCellText(rowIndex, 3, row.change);
        table->SetCellHorizontalAlignment(rowIndex, 1, W::JustificationValues::Right);
        table->SetCellHorizontalAlignment(rowIndex, 2, W::JustificationValues::Right);
        table->SetCellHorizontalAlignment(rowIndex, 3, W::JustificationValues::Right);
        ++rowIndex;
    }

    table->MergeCells(4, 0, 1, 4);
    table->SetCellText(4, 0, "Total: 3 805 units, 258 800 in revenue.");
    table->SetCellBackgroundColor(4, 0, Color(0xEB, 0xF1, 0xFA));

    // --- Images. --------------------------------------------------------------
    editor->AddHeading("Images", 2);
    editor->AddParagraph("Image bytes are stored as a package part; the format, pixel size, and DPI "
                         "are detected from the bytes themselves:");

    auto image = editor->AddImageFromData(ExyokiOfficeExamples::BuildGradientBmp(480, 240));
    if (!image)
    {
        std::cerr << "Failed to insert the image.\n";
        return 1;
    }
    image->SetSize(Millimeters(120.0), Millimeters(60.0))
        .SetAltText("Gradient", "A generated blue-to-red gradient used as sample artwork.");

    // AddParagraph(text) would create an unformatted run, so the caption text is
    // added as an explicitly styled run instead.
    auto caption = editor->AddParagraph();
    caption->SetAlignment(W::JustificationValues::Center);
    caption->AddRun("Figure 1: a gradient generated at run time, so the example needs no asset files.",
                    RunStyle{.Italic = true, .FontSize = Points(9.0)});

    // --- Hyperlinks, bookmarks, fields, notes, comments, content controls. ---
    editor->AddHeading("References and review markup", 2);

    auto links = editor->AddParagraph();
    links->AddText("The format itself is documented publicly: ");
    links->AddHyperlink("Office Open XML on Wikipedia", "https://en.wikipedia.org/wiki/Office_Open_XML",
                        "Opens in a browser");
    links->AddText(". Internal navigation uses bookmarks — ");
    links->AddInternalHyperlink("back to the title", "Title");
    links->AddText(".");

    auto fields = editor->AddParagraph(FieldsText);
    fields->SetAlignment(W::JustificationValues::Both);
    fields->AddEndnote("Word recomputes dirty fields on open, or on demand with Ctrl+A followed by F9.");

    auto review = editor->AddParagraph("This sentence carries a review comment and a content control.");
    review->AddCommentOnParagraph("Check the wording before publishing.",
                                  CommentAuthor{.Name = "Reviewer", .Initials = "RV"});
    review->AddInlineContentControl("customerName", "Customer name");

    auto stamp = editor->AddParagraph();
    stamp->AddText("Generated on ");
    stamp->AddSimpleField("DATE \\@ \"yyyy-MM-dd\"", "2026-01-01");
    stamp->AddText(" by ExyokiOffice.");

    // A placeholder written across three runs, so the replacement below has to
    // work across run boundaries the way a real template fill-in does.
    auto placeholder = editor->AddParagraph();
    placeholder->AddText("Prepared for {{CUS");
    placeholder->AddRun("TOM", RunStyle{.Bold = true});
    placeholder->AddText("ER}} by the documentation team.");

    // --- A find-and-replace pass across run boundaries. ----------------------
    ExyokiOffice::Size replacements = 0;
    for (const auto& paragraph : editor->Paragraphs())
    {
        replacements += paragraph->ReplaceAll("{{CUSTOMER}}", "Contoso Ltd.");
    }

    // --- Page setup, header, and footer with a page-number field. ------------
    auto section = editor->EnsureFinalSection();
    section->SetPageSize({Millimeters(210.0), Millimeters(297.0), PageOrientation::Portrait});
    // Designated initializers, so the order of SectionMargins' seven identically
    // typed members cannot be mixed up silently.
    section->SetMargins({.Top = Millimeters(25.0),
                         .Right = Millimeters(20.0),
                         .Bottom = Millimeters(25.0),
                         .Left = Millimeters(20.0),
                         .Header = Millimeters(12.5),
                         .Footer = Millimeters(12.5),
                         .Gutter = {}});
    section->SetHeaderText(HeaderFooterType::Default, "ExyokiOffice Editor Example");

    auto footer = section->EnsureFooter(HeaderFooterType::Default);
    if (!footer)
    {
        std::cerr << "Failed to create the footer.\n";
        return 1;
    }
    footer->Clear();
    auto footerParagraph = footer->AddParagraph();
    footerParagraph->SetAlignment(W::JustificationValues::Center);
    footerParagraph->AddText("Page ");
    footerParagraph->AddField("PAGE", "1");
    footerParagraph->AddText(" of ");
    footerParagraph->AddField("NUMPAGES", "1");

    // --- Save and verify by re-opening. --------------------------------------
    const char* fileName = "ExampleWordEditor.docx";
    if (!editor->SaveToFile(fileName))
    {
        std::cerr << "Failed to write " << fileName << ".\n";
        return 1;
    }

    auto reopened = WordDocumentEditor::Open(fileName);
    if (!reopened)
    {
        std::cerr << "Failed to re-open " << fileName << ".\n";
        return 1;
    }

    std::cout << "Generated " << fileName << ": " << reopened->Paragraphs().size() << " paragraphs, "
              << reopened->Tables().size() << " table(s), " << reopened->Bookmarks().size()
              << " bookmark(s), " << reopened->Fields().size() << " field(s), "
              << reopened->Footnotes().size() << " footnotes-part entries (Word's separators included), "
              << reopened->Comments().size() << " comment(s), " << replacements
              << " text replacement(s).\n"
              << "Open it in Word and press Ctrl+A, F9 to build the table of contents.\n";
    return 0;
}
