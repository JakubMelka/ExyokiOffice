// A one-page showcase document: the kind of page you would hand to somebody who
// asks what ExyokiOffice produces. It is deliberately short and deliberately
// dense - the repository logo, a title block, prose, a bulleted list, a
// formatted table with a header row and a merged summary row, a code callout, a
// hyperlink, and a footer with page fields - all written through the public
// high-level API and all fitting on a single A4 page.
//
// This is the marketing sibling of examples/ExampleWordEditor, which is the
// exhaustive API tour and runs to several pages; examples/ExampleWordEdit
// covers editing an existing document, and examples/ExampleWord the typed DOM
// and packaging layers underneath.
#include "ExyokiOffice/StandardTypes.hpp"
#include "ExyokiOffice/Version.hpp"
#include "ExyokiOffice/Word/WordDocument.hpp"

#include <filesystem>
#include <iostream>
#include <optional>
#include <string>
#include <string_view>

using namespace ExyokiOffice::Word;
namespace W = ExyokiOffice::DocumentFormat::OpenXml::Wordprocessing;
using ExyokiOffice::Color;
using ExyokiOffice::MeasurementUnit;
using ExyokiOffice::MeasuringUnits;

namespace ExampleWordDemo
{

MeasuringUnits Millimeters(ExyokiOffice::Real value)
{
    return MeasuringUnits(value, MeasurementUnit::Millimeter);
}

MeasuringUnits Points(ExyokiOffice::Real value)
{
    return MeasuringUnits(value, MeasurementUnit::Point);
}

// The house colors of the logo, reused by the title, the callout and the table
// so the page reads as one design rather than as a pile of features.
const Color BrandDark(0x0F, 0x2E, 0x54);
const Color BrandBlue(0x1F, 0x76, 0xD2);
const Color BrandTint(0xED, 0xF3, 0xFB);
const Color BrandGray(0x5A, 0x66, 0x74);

// The logo lives in the repository root. The example runs from its own working
// directory under the build tree, so the path is resolved against the source
// directory the build baked in.
std::filesystem::path LogoPath()
{
    return std::filesystem::path(EXYOKIOFFICE_SOURCE_DIR) / "LOGO.png";
}

constexpr std::string_view TaglineText =
    "Everything on this page - the logo, the headings, the list, the table, the code box and the "
    "page number in the footer - was written by a small C++ program through the public ExyokiOffice "
    "API. No Microsoft Office and no .NET runtime took part.";

constexpr std::string_view ClosingText =
    "The same library writes workbooks and presentations, ships the exyoki command-line tool, and "
    "exposes all three document families to AI agents over the Model Context Protocol. ";

} // namespace ExampleWordDemo

int main()
{
    using namespace ExampleWordDemo;

    auto editor = WordDocumentEditor::CreateNew();
    if (!editor)
    {
        std::cerr << "Failed to create the document.\n";
        return 1;
    }

    // --- Document properties, which is what a document manager shows. --------
    auto properties = editor->Properties();
    properties.SetTitle("Created with ExyokiOffice");
    properties.SetCreator("ExyokiOffice Library");
    properties.SetSubject("One-page showcase of the Word authoring API");
    properties.SetKeywords("ExyokiOffice, OpenXML, docx, C++");
    properties.SetDescription("Generated by examples/ExampleWordDemo.");
    properties.SetCategory("Samples");
    properties.SetCompany("ExyokiOffice");

    // --- Page setup first, so the content below is laid out against it. ------
    auto section = editor->EnsureFinalSection();
    if (!section)
    {
        std::cerr << "Failed to create the section.\n";
        return 1;
    }
    section->SetPageSize({Millimeters(210.0), Millimeters(297.0), PageOrientation::Portrait});
    section->SetMargins({.Top = Millimeters(15.0),
                         .Right = Millimeters(20.0),
                         .Bottom = Millimeters(15.0),
                         .Left = Millimeters(20.0),
                         .Header = Millimeters(10.0),
                         .Footer = Millimeters(8.0),
                         .Gutter = {}});

    // --- The logo, at an explicit size rather than its native 1707 pixels. ---
    auto logo = editor->AddImageFromFile(LogoPath(), Millimeters(110.0), Millimeters(59.4));
    if (!logo)
    {
        std::cerr << "Failed to insert " << LogoPath().string() << ".\n";
        return 1;
    }
    logo->SetAltText("ExyokiOffice", "The ExyokiOffice project logo.");

    // AddImageFromFile appends the picture in a paragraph of its own, so the
    // paragraph that now ends the body is the one holding it.
    auto logoParagraph = editor->Paragraphs().back();
    logoParagraph->SetAlignment(W::JustificationValues::Center)
        .SetSpacing(std::nullopt, Points(6.0), std::nullopt);

    // --- Title block. ---------------------------------------------------------
    auto title = editor->AddParagraph();
    title->SetAlignment(W::JustificationValues::Center)
        .SetSpacing(std::nullopt, Points(2.0), std::nullopt);
    title->AddRun("Created with ExyokiOffice",
                  RunStyle{.Bold = true, .FontSize = Points(26.0), .Color = BrandDark});

    auto tagline = editor->AddParagraph();
    tagline->SetAlignment(W::JustificationValues::Both)
        .SetIndentation(Millimeters(10.0), Millimeters(10.0), std::nullopt, std::nullopt)
        .SetSpacing(std::nullopt, Points(14.0), std::nullopt);
    tagline->AddRun(TaglineText, RunStyle{.FontSize = Points(11.0), .Color = BrandGray});

    // --- A bulleted list. -----------------------------------------------------
    editor->AddHeading("What the library does", 2)
        ->SetSpacing(std::nullopt, Points(4.0), std::nullopt);

    // The default glyph is an ASCII asterisk. U+2022 BULLET reads better and
    // needs no Symbol font, and it is written as escaped UTF-8 bytes because the
    // MSVC build does not pass /utf-8 and the sources carry no byte order mark.
    auto bullets = editor->EnsureBulletedListStyle("DemoBullets", "\xE2\x80\xA2");
    for (const auto* item :
         {"Creates and edits .docx, .xlsx and .pptx by writing the ZIP and its XML parts directly.",
          "A high-level editor per format, and a typed OpenXML DOM for the exact element.",
          "Keeps the markup it does not model, so editing never quietly drops content.",
          "One C++20 shared library, MIT licensed, with no Office and no .NET dependency."})
    {
        auto bullet = editor->AddParagraph(item);
        bullet->SetListStyle(bullets).SetSpacing(std::nullopt, Points(2.0), std::nullopt);
    }

    // --- A formatted table with a header row and a merged summary row. -------
    editor->AddHeading("Three formats, one API", 2)
        ->SetSpacing(Points(10.0), Points(4.0), std::nullopt);

    auto table = editor->AddTable(5, 3);
    if (!table)
    {
        std::cerr << "Failed to create the table.\n";
        return 1;
    }
    table->SetWidth(Millimeters(170.0))
        .SetAlignment(W::TableRowAlignmentValues::center)
        .SetBorders(W::BorderValues::Single, ExyokiOffice::UInt32{4}, BrandBlue)
        .SetDefaultCellMargins(Millimeters(2.0), Millimeters(1.0), Millimeters(2.0), Millimeters(1.0));
    table->SetColumnWidth(0, Millimeters(34.0));
    table->SetColumnWidth(1, Millimeters(24.0));
    table->SetColumnWidth(2, Millimeters(112.0));

    // Table::Paragraphs() hands back one paragraph per cell in row-major order,
    // which is how the still-empty header cells get formatted runs instead of
    // the plain text SetCellText() writes.
    const char* headers[] = {"Format", "File", "What you can build"};
    auto cells = table->Paragraphs();
    for (ExyokiOffice::Size column = 0; column < 3; ++column)
    {
        cells[column]->AddRun(headers[column],
                              RunStyle{.Bold = true,
                                       .FontSize = Points(10.0),
                                       .Color = Color(0xFF, 0xFF, 0xFF)});
        table->SetCellBackgroundColor(0, column, BrandDark);
    }
    table->SetRowHeader(0, true);

    const struct
    {
        const char* format;
        const char* extension;
        const char* description;
    } rows[] = {
        {"Word", ".docx", "Reports and letters with styles, tables, images, fields."},
        {"Excel", ".xlsx", "Workbooks with formulas, charts, pivot tables, slicers."},
        {"PowerPoint", ".pptx", "Decks with layouts, shapes, media, charts, animations."},
    };
    ExyokiOffice::Size rowIndex = 1;
    for (const auto& row : rows)
    {
        table->SetCellText(rowIndex, 0, row.format);
        table->SetCellText(rowIndex, 1, row.extension);
        table->SetCellText(rowIndex, 2, row.description);
        if (rowIndex % 2 == 1)
        {
            for (ExyokiOffice::Size column = 0; column < 3; ++column)
            {
                table->SetCellBackgroundColor(rowIndex, column, BrandTint);
            }
        }
        ++rowIndex;
    }

    table->MergeCells(4, 0, 1, 3);
    table->SetCellText(4, 0, "Every row above is reachable from C++, from the exyoki command line "
                             "and from an AI agent over MCP.");
    table->SetCellHorizontalAlignment(4, 0, W::JustificationValues::Center);

    // --- A code callout. Word draws one box around consecutive paragraphs only
    // --- when their borders match exactly, so the snippet is a single
    // --- paragraph with explicit line breaks instead of five paragraphs.
    editor->AddHeading("The code behind this page", 2)
        ->SetSpacing(Points(10.0), Points(4.0), std::nullopt);

    const RunStyle codeStyle{.AsciiFont = "Consolas",
                             .HighAnsiFont = "Consolas",
                             .FontSize = Points(9.0),
                             .Color = BrandDark};
    auto code = editor->AddParagraph();
    code->SetShading(BrandTint)
        .SetBorders(W::BorderValues::Single, ExyokiOffice::UInt32{6}, BrandBlue, Points(6.0))
        .SetIndentation(Millimeters(4.0), Millimeters(4.0), std::nullopt, std::nullopt)
        .SetSpacing(std::nullopt, Points(12.0), std::nullopt);

    const char* codeLines[] = {
        "auto editor = WordDocumentEditor::CreateNew();",
        "editor->AddImageFromFile(\"LOGO.png\", Millimeters(110.0), Millimeters(59.4));",
        "editor->AddHeading(\"Created with ExyokiOffice\", 1);",
        "editor->AddParagraph(\"Ready in a handful of lines.\");",
        "editor->SaveToFile(\"ExampleWordDemo.docx\");",
    };
    bool firstCodeLine = true;
    for (const auto* line : codeLines)
    {
        if (!firstCodeLine)
        {
            code->AddBreak();
        }
        firstCodeLine = false;
        code->AddRun(line, codeStyle);
    }

    // --- Closing line with a hyperlink. --------------------------------------
    auto closing = editor->AddParagraph();
    closing->SetAlignment(W::JustificationValues::Both);
    closing->AddRun(ClosingText, RunStyle{.FontSize = Points(11.0), .Color = BrandGray});
    auto link = closing->AddHyperlink("Read the documentation on GitHub",
                                      "https://github.com/JakubMelka/ExyokiOffice",
                                      "Opens the ExyokiOffice repository");
    if (!link)
    {
        std::cerr << "Failed to insert the hyperlink.\n";
        return 1;
    }

    // A new document carries no built-in Hyperlink character style, so the link
    // would otherwise inherit the surrounding prose. Style its runs explicitly.
    for (const auto& run : link->Runs())
    {
        run->SetColor(BrandBlue)
            .SetUnderline(W::UnderlineValues(W::UnderlineValues::Single))
            .SetFontSize(Points(11.0));
    }

    closing->AddRun(".", RunStyle{.FontSize = Points(11.0), .Color = BrandGray});

    // --- Footer with the linked library version and page fields. -------------
    auto footer = section->EnsureFooter(HeaderFooterType::Default);
    if (!footer)
    {
        std::cerr << "Failed to create the footer.\n";
        return 1;
    }
    footer->Clear();

    const RunStyle footerStyle{.FontSize = Points(8.0), .Color = BrandGray};
    auto footerParagraph = footer->AddParagraph();
    footerParagraph->SetAlignment(W::JustificationValues::Center);
    footerParagraph->AddRun("Generated by ExyokiOffice " + std::string(ExyokiOffice::GetVersion()) +
                                " - examples/ExampleWordDemo - page ",
                            footerStyle);
    footerParagraph->AddField("PAGE", "1");
    footerParagraph->AddRun(" of ", footerStyle);
    footerParagraph->AddField("NUMPAGES", "1");

    // --- Save, then re-open to prove the package round-trips. ----------------
    const char* fileName = "ExampleWordDemo.docx";
    if (!editor->SaveToFile(fileName))
    {
        std::cerr << "Failed to write " << fileName << ".\n";
        return 1;
    }

    auto reopened = WordDocumentEditor::Open(fileName);
    if (!reopened)
    {
        std::cerr << "Failed to re-open " << fileName << ".\n";
        return 1;
    }

    ExyokiOffice::Size images = 0;
    for (const auto& paragraph : reopened->Paragraphs())
    {
        images += paragraph->Images().size();
    }

    std::cout << "Generated " << fileName << ": " << reopened->Paragraphs().size() << " paragraphs, "
              << reopened->Tables().size() << " table(s), " << images << " image(s).\n"
              << "Open it in Word - it is a single page.\n";
    return 0;
}
