std::vector<ExyokiOffice::Byte> Bytes(std::string_view text)
{
    return std::vector<ExyokiOffice::Byte>(text.begin(), text.end());
}

std::vector<ExyokiOffice::Byte> FromHex(std::string_view text)
{
    std::vector<ExyokiOffice::Byte> result;
    result.reserve(text.size() / 2);
    for (ExyokiOffice::Size index = 0; index + 1 < text.size(); index += 2)
    {
        result.push_back(static_cast<ExyokiOffice::UInt8>(std::stoul(std::string(text.substr(index, 2)), nullptr, 16)));
    }
    return result;
}

std::string ToHex(const std::vector<ExyokiOffice::Byte>& value)
{
    static constexpr char kDigits[] = "0123456789abcdef";
    std::string result;
    result.reserve(value.size() * 2);
    for (const auto byte : value)
    {
        result.push_back(kDigits[byte >> 4]);
        result.push_back(kDigits[byte & 0x0FU]);
    }
    return result;
}

/// A zero spin count reduces the verifier to a single hash of salt+password,
/// so passing the message as the salt yields the plain digest of that message.
std::string DigestOf(PasswordHashAlgorithm algorithm, std::string_view message)
{
    return ToHex(OfficePasswordVerifier::ComputeVerifier(algorithm, {}, Bytes(message), 0));
}

