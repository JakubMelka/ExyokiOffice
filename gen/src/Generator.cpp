void Generator::Run()
{
    GeneratorText::UnhandledProperties().Clear();

    if (!std::filesystem::exists(config_.dataRoot))
    {
        throw std::runtime_error("Data root does not exist: " + config_.dataRoot.string());
    }

    const auto namespacesPath = config_.dataRoot / "namespaces.json";
    if (!std::filesystem::exists(namespacesPath))
    {
        throw std::runtime_error("Namespace file does not exist: " + namespacesPath.string());
    }

    auto knownNamespaces = GeneratorSchemaReader::LoadNamespaceRecords(namespacesPath);
    auto namespaceRegistry = GeneratorSchemaReader::BuildNamespaceLookup(knownNamespaces);

    if (config_.generateNamespaces)
    {
        Logger::Info("Generating namespace registry...");
        GeneratorSchemaReader::WriteNamespaceRegistryFiles(config_, knownNamespaces);
        Logger::Info("Generated " + std::to_string(knownNamespaces.size()) + " namespace definitions.");
    }
    else
    {
        Logger::Info("Namespace generation disabled.");
    }

    if (!config_.generateSchema)
    {
        Logger::Info("Schema generation disabled.");
        GeneratorText::UnhandledProperties().EmitWarnings();
        return;
    }

    const auto schemasDir = config_.dataRoot / "schemas";
    if (!std::filesystem::exists(schemasDir))
    {
        throw std::runtime_error("Schema data directory does not exist: " + schemasDir.string());
    }

    Logger::Info("Loading strongly typed namespaces...");
    auto namespaces = GeneratorSchemaReader::LoadTypedNamespaces(config_.dataRoot / "typed" / "namespaces.json");
    std::unordered_map<std::string, TypedNamespace> typedNamespaceMap;
    for (const auto& ns : namespaces)
    {
        typedNamespaceMap.emplace(ns.prefix, ns);
    }

    Logger::Info("Loading schema definitions (enums and types)...");
    auto schemaData = GeneratorSchemaReader::LoadSchemaElements(schemasDir, namespaceRegistry);
    GeneratorSchemaReader::ApplyParticleOverlay(schemaData, config_.dataRoot / "exyokioffice_particle_extras.json");
    const auto totalElements = schemaData.elements.size();
    std::vector<SchematronRule> packageSchematronRules;
    const auto schematronsPath = config_.dataRoot / "schematrons.json";
    if (std::filesystem::exists(schematronsPath))
    {
        Logger::Info("Loading schematron rules...");
        const auto schematronRules = LoadSchematronRules(schematronsPath);
        // An element name can belong to several types - `w:bottom` is a border
        // inside `w:pBdr` and a table width inside `w:tblCellMar` - and the
        // schematron source names only the element. Every candidate is kept so
        // that a rule can be attached to the ones whose attributes it fits.
        std::unordered_multimap<std::string, TypedElement*> elementByName;
        for (auto& element : schemaData.elements)
        {
            if (!element.elementQualifiedName.empty())
            {
                elementByName.emplace(element.elementQualifiedName, &element);
                if (element.elementQualifiedName.rfind("o:", 0) == 0)
                {
                    elementByName.emplace("ovml:" + element.elementQualifiedName.substr(2), &element);
                }
            }
        }
        const auto elementsByClassName = GeneratorValidatorExpressions::BuildTypedElementsByClassName(schemaData.elements);
        std::size_t retargetedSchematrons = 0;
        std::size_t skippedSchematrons = 0;

        std::size_t supportedSchematrons = 0;
        std::size_t generatedSchematrons = 0;
        for (const auto& rule : schematronRules)
        {
            if (rule.kind == SchematronPatternKind::Unsupported)
            {
                Logger::Warn({"GEN-UNSUPPORTED-SCHEMATRON",
                              "schematron",
                              "Unsupported schematron test for '" + rule.context + "': " + rule.test,
                              rule.sourceFile,
                              "schematron rule",
                              rule.context,
                              rule.test});
                continue;
            }

            ++supportedSchematrons;
            const auto candidates = elementByName.equal_range(rule.context);
            const auto foundElement = candidates.first;
            if (foundElement == elementByName.end() || candidates.first == candidates.second)
            {
                Logger::Warn({"GEN-SCHEMATRON-CONTEXT-NOT-FOUND",
                              "schematron",
                              "Schematron context '" + rule.context + "' does not match a generated element.",
                              rule.sourceFile,
                              "schematron rule",
                              rule.context,
                              rule.test});
                continue;
            }

            if (!GeneratorValidatorExpressions::IsElementLocalSchematronRule(rule.kind))
            {
                if (rule.kind == SchematronPatternKind::RelationshipExists || rule.kind == SchematronPatternKind::RelationshipType || rule.kind == SchematronPatternKind::UniqueValues || rule.kind == SchematronPatternKind::AncestorUniqueValues || rule.kind == SchematronPatternKind::PartReferenceExists || rule.kind == SchematronPatternKind::PartCountComparison)
                {
                    packageSchematronRules.push_back(rule);
                    ++generatedSchematrons;
                    continue;
                }

                Logger::Warn({"GEN-SCHEMATRON-CONSTRAINT-NOT-GENERATED",
                              "schematron",
                              "Schematron rule for '" + rule.context + "' is recognized as '" + std::string(ToString(rule.kind)) + "' but requires package/tree validation codegen: " + rule.test,
                              rule.sourceFile,
                              "schematron rule",
                              rule.context,
                              rule.test});
                continue;
            }

            // The rule belongs to those candidates that can carry the attribute
            // it talks about, with its name resolved to what they declare.
            bool attached = false;
            for (auto candidate = candidates.first; candidate != candidates.second; ++candidate)
            {
                auto& element = *candidate->second;
                const auto requestedQName = GeneratorValidatorExpressions::ResolveSchematronAttributeName(rule, element);
                const auto* declared = GeneratorValidatorExpressions::FindDeclaredAttribute(element, requestedQName, elementsByClassName);
                if (!declared)
                {
                    continue;
                }

                if (!declared->qName.prefix.empty() &&
                    namespaceRegistry.find(declared->qName.prefix) == namespaceRegistry.end())
                {
                    Logger::Warn({"GEN-SCHEMATRON-CONSTRAINT-NOT-GENERATED",
                                  "schematron",
                                  "Schematron rule for '" + rule.context + "' uses unknown attribute namespace prefix '" +
                                      declared->qName.prefix + "': " + rule.test,
                                  rule.sourceFile,
                                  "schematron rule",
                                  rule.context,
                                  rule.test});
                    continue;
                }

                auto attachedRule = rule;
                const auto resolvedName = declared->qName.prefix.empty()
                                              ? declared->qName.localName
                                              : declared->qName.prefix + ":" + declared->qName.localName;
                if (attachedRule.operands.front() != resolvedName)
                {
                    ++retargetedSchematrons;
                }
                attachedRule.operands.front() = resolvedName;
                element.schematronRules.push_back(std::move(attachedRule));
                attached = true;
            }

            if (!attached)
            {
                // No candidate declares the attribute, so the rule cannot be
                // checked against any of them. Attaching it to an arbitrary one
                // would report every valid document as missing an attribute the
                // element is not even allowed to carry.
                ++skippedSchematrons;
                continue;
            }
            ++generatedSchematrons;
        }

        Logger::Info("Recognized " + std::to_string(supportedSchematrons) + " of " + std::to_string(schematronRules.size()) + " schematron rules.");
        Logger::Info("Generated metadata constraints for " + std::to_string(generatedSchematrons) + " schematron rules.");
        Logger::Info("Retargeted " + std::to_string(retargetedSchematrons) +
                     " schematron attribute names onto the attribute the element declares.");
        Logger::Info("Skipped " + std::to_string(skippedSchematrons) +
                     " schematron rules whose attribute no element of that name declares.");
    }
    GeneratorSchematronWriter::WriteGeneratedSchematronRules(config_, packageSchematronRules, namespaceRegistry);
    EnumFacetLookup enumFacetLookup;
    for (const auto& enumDefinition : schemaData.enums)
    {
        auto& values = enumFacetLookup[enumDefinition.typeQualifiedName];
        values.reserve(enumDefinition.facets.size());
        for (const auto& facet : enumDefinition.facets)
        {
            values.push_back(facet.value);
        }
    }
    std::vector<FactoryElementInfo> factoryElements;
    factoryElements.reserve(totalElements);
    std::unordered_set<std::string> factoryNamespaceUsage;

    // Ordered by prefix on purpose. Several prefixes can share one API
    // namespace, and their elements are concatenated into a single header in
    // the order the groups are visited, so an unordered container would emit
    // the same data in a different order on every standard library.
    std::map<std::string, std::vector<EnumDefinition>> groupedEnums;
    for (auto& enumDef : schemaData.enums)
    {
        groupedEnums[enumDef.namespacePrefix].push_back(std::move(enumDef));
    }
    std::map<std::string, std::vector<TypedElement>> groupedElements;
    for (auto& element : schemaData.elements)
    {
        groupedElements[element.namespacePrefix].push_back(std::move(element));
    }

    auto ensureTypedNamespace = [&](const std::string& prefix) -> const TypedNamespace&
    {
        if (auto it = typedNamespaceMap.find(prefix); it != typedNamespaceMap.end())
        {
            return it->second;
        }

        Logger::Warn({"GEN-MISSING-TYPED-NAMESPACE",
                      "namespace-resolution",
                      "Typed namespace definition missing for prefix '" + prefix + "'. Falling back to namespace 'DocumentFormat.OpenXml." + prefix + "'.",
                      {},
                      "namespace",
                      prefix});
        auto [it, _] = typedNamespaceMap.emplace(prefix, TypedNamespace{prefix, "DocumentFormat.OpenXml." + prefix});
        return it->second;
    };

    for (const auto& [prefix, _] : groupedEnums)
    {
        ensureTypedNamespace(prefix);
    }
    for (const auto& [prefix, _] : groupedElements)
    {
        ensureTypedNamespace(prefix);
    }

    EnumIncludeLookup enumIncludeLookup;
    for (const auto& [prefix, enumsForPrefix] : groupedEnums)
    {
        const auto& ns = ensureTypedNamespace(prefix);
        const auto includePath = GeneratorSchemaReader::BuildEnumIncludePath(ns.apiNamespace);
        for (const auto& enumDef : enumsForPrefix)
        {
            const auto qualifiedName = GeneratorSchemaReader::BuildEnumQualifiedName(enumDef.className, ns.apiNamespace);
            enumIncludeLookup.emplace(qualifiedName, EnumIncludeInfo{includePath, ns.apiNamespace});
        }
    }

    std::map<std::string, AggregatedNamespaceData> aggregatedNamespaces;
    std::vector<TypedNamespace> resolvedNamespaces;
    resolvedNamespaces.reserve(groupedElements.size() + groupedEnums.size());
    std::unordered_set<std::string> registeredPrefixes;
    RootElementLookup rootLookup;
    PartRootLookup partRootLookup;

    auto acquireAggregation = [&](const std::string& prefix) -> AggregatedNamespaceData&
    {
        const auto& ns = ensureTypedNamespace(prefix);
        if (!registeredPrefixes.contains(prefix))
        {
            registeredPrefixes.insert(prefix);
            resolvedNamespaces.push_back(ns);
        }

        auto& entry = aggregatedNamespaces[ns.apiNamespace];
        if (entry.ns.apiNamespace.empty())
        {
            entry.ns = ns;
        }
        return entry;
    };

    for (auto& [prefix, enumsForPrefix] : groupedEnums)
    {
        auto& entry = acquireAggregation(prefix);
        entry.enums.insert(entry.enums.end(),
                           std::make_move_iterator(enumsForPrefix.begin()),
                           std::make_move_iterator(enumsForPrefix.end()));
    }

    for (auto& [prefix, elementsForPrefix] : groupedElements)
    {
        auto& entry = acquireAggregation(prefix);
        entry.elements.insert(entry.elements.end(),
                              std::make_move_iterator(elementsForPrefix.begin()),
                              std::make_move_iterator(elementsForPrefix.end()));
    }

    std::unordered_map<std::string, std::string> typeLookup;
    std::unordered_map<std::string, std::string> elementLookup;
    // Compound (schema type, element name) lookup. Schema types are frequently
    // shared by several elements (x:CT_BooleanProperty backs x:b, x:i, and
    // friends), so a type-only lookup would return the type's first registrant.
    std::unordered_map<std::string, std::string> typeElementLookup;
    // Element QNames claimed by more than one class. Those cannot be resolved
    // from the element name alone, so particle metadata resolves them by schema
    // type and the runtime factory falls back to the parent's content model.
    std::unordered_set<std::string> ambiguousElements;
    for (const auto& [apiNamespace, aggregation] : aggregatedNamespaces)
    {
        (void)apiNamespace;
        for (const auto& element : aggregation.elements)
        {
            auto className = GeneratorSchemaReader::BuildClassQualifiedName(element.className, aggregation.ns.apiNamespace);
            typeLookup.emplace(element.typeQualifiedName, className);
            if (element.hasElementQualifiedName)
            {
                typeElementLookup.emplace(
                    GeneratorValidatorExpressions::MakeTypeElementKey(element.typeQualifiedName, element.elementQualifiedName), className);
                const auto [position, inserted] =
                    elementLookup.emplace(element.elementQualifiedName, className);
                if (!inserted && position->second != className)
                {
                    ambiguousElements.insert(element.elementQualifiedName);
                }
            }
        }
    }

    // First valid facet of every enum, keyed by its fully-qualified C++ type.
    // Used by the DOM test emitter to synthesize a defined enum sample value.
    // Built across all namespaces first, because an attribute may reference an
    // enum declared in a different namespace.
    std::unordered_map<std::string, std::string> enumFirstFacet;
    for (const auto& [apiNamespace, aggregation] : aggregatedNamespaces)
    {
        (void)apiNamespace;
        for (const auto& enumDef : aggregation.enums)
        {
            if (enumDef.facets.empty())
            {
                continue;
            }
            const auto qualifiedName = GeneratorSchemaReader::BuildEnumQualifiedName(enumDef.className, aggregation.ns.apiNamespace);
            enumFirstFacet.emplace(qualifiedName, enumDef.facets.front().name);
        }
    }

    std::size_t generatedNamespaces = 0;
    for (auto& [apiNamespace, aggregation] : aggregatedNamespaces)
    {
        (void)apiNamespace;
        auto orderedElements = GeneratorValidatorExpressions::TopologicallyOrderElements(aggregation.elements, aggregation.ns.apiNamespace);

        GeneratorNamespaceWriter::WriteNamespaceEnumHeader(config_, aggregation.ns, aggregation.enums);
        GeneratorNamespaceWriter::WriteNamespaceHeader(config_, aggregation.ns, aggregation.enums, orderedElements, namespaceRegistry, enumIncludeLookup);
        GeneratorNamespaceWriter::WriteNamespaceSource(config_, aggregation.ns, aggregation.enums, orderedElements, namespaceRegistry, typeLookup,
                                                       elementLookup, typeElementLookup, ambiguousElements, enumFacetLookup);
        if (config_.generateTests)
        {
            GeneratorDomTestWriter::WriteGeneratedDomTests(config_, aggregation.ns, orderedElements, enumFirstFacet);
        }
        const auto includeHeader =
            (std::filesystem::path("ExyokiOffice") / "DOM" / GeneratorSchemaReader::NamespaceToPath(aggregation.ns.apiNamespace)).generic_string();
        for (const auto& element : orderedElements)
        {
            if (!element.hasElementQualifiedName || element.elementQualifiedName.empty())
            {
                continue;
            }

            RootElementInfo info;
            info.classQualifiedName = GeneratorSchemaReader::BuildClassQualifiedName(element.className, aggregation.ns.apiNamespace);
            info.includeHeader = includeHeader;
            info.versionExpression = element.versionExpression;
            rootLookup.emplace(element.elementQualifiedName, info);
            if (!element.partClassName.empty())
            {
                const auto [_, inserted] = partRootLookup.emplace(element.partClassName, info);
                if (!inserted)
                {
                    throw std::runtime_error("Multiple schema roots are assigned to part '" + element.partClassName + "'.");
                }
            }
        }
        GeneratorSchemaReader::CollectFactoryElements(orderedElements, aggregation.ns, namespaceRegistry, factoryElements, factoryNamespaceUsage);
        ++generatedNamespaces;
    }

    GeneratorNamespaceWriter::WriteTypedNamespaceIndex(config_, resolvedNamespaces);
    std::vector<std::string> factoryNamespaces(factoryNamespaceUsage.begin(), factoryNamespaceUsage.end());
    std::sort(factoryNamespaces.begin(), factoryNamespaces.end());
    GeneratorDomTestWriter::WriteOpenXmlElementFactory(config_, factoryElements, factoryNamespaces);

    if (config_.generateParts)
    {
        Logger::Info("Generating packaging parts...");
        const auto partsDir = config_.dataRoot / "parts";
        auto partsData = GeneratorSchemaReader::LoadPartDefinitions(partsDir);
        GeneratorSchemaReader::ApplyPartPathOverlay(partsData, config_.dataRoot / "exyokioffice_part_paths.json");
        GeneratorPartsWriter::WriteGeneratedParts(config_, partsData, rootLookup, partRootLookup);
        GeneratorPartsWriter::WritePackageFactory(config_, partsData);
        Logger::Info("Generated " + std::to_string(partsData.parts.size()) + " part descriptors and " + std::to_string(partsData.packages.size()) + " packages.");
    }
    else
    {
        Logger::Info("Part generation disabled.");
    }

    GeneratorText::UnhandledProperties().EmitWarnings();
    Logger::Info("Generated " + std::to_string(generatedNamespaces) + " typed namespace headers with " + std::to_string(totalElements) + " element descriptors.");
}
