class UnhandledPropertyTracker
{
public:
    void Clear() noexcept
    {
        entries_.clear();
        seen_.clear();
    }

    void Record(std::string_view property,
                std::string_view ownerKind,
                std::string_view ownerName,
                std::string_view sourceFile)
    {
        std::string key;
        key.reserve(property.size() + ownerKind.size() + ownerName.size() + sourceFile.size() + 3);
        key.append(property);
        key.push_back('|');
        key.append(ownerKind);
        key.push_back('|');
        key.append(ownerName);
        key.push_back('|');
        key.append(sourceFile);

        if (!seen_.insert(key).second)
        {
            return;
        }

        entries_.push_back({std::string(property),
                            std::string(ownerKind),
                            std::string(ownerName),
                            std::string(sourceFile)});
    }

    void EmitWarnings() const
    {
        for (const auto& entry : entries_)
        {
            std::string description = entry.ownerKind;
            if (!entry.ownerName.empty())
            {
                description += " '";
                description += entry.ownerName;
                description += '\'';
            }

            const auto message = "Ignoring JSON property '" + entry.property + "' for " + description + " defined in '" + entry.sourceFile + "'.";
            Logger::Warn({"GEN-IGNORED-PROPERTY",
                          "ignored-property",
                          message,
                          entry.sourceFile,
                          entry.ownerKind,
                          entry.ownerName,
                          entry.property});
        }
    }

private:
    std::vector<UnhandledPropertyEntry> entries_;
    std::unordered_set<std::string> seen_;
};

